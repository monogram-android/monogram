package org.monogram.data.db.model

import androidx.room.Entity
import androidx.room.Index

@Entity(
    tableName = "messages",
    primaryKeys = ["chatId", "id"],
    indices = [
        Index(value = ["chatId", "date"]),
        Index(value = ["chatId", "id"]),
        Index(value = ["createdAt"])
    ]
)
data class MessageEntity(
    val id: Long,
    val chatId: Long,
    val senderId: Long,
    val senderName: String = "",
    val content: String,
    val contentType: String = "text",
    val contentMeta: String? = null,
    val mediaFileId: Int = 0,
    val mediaPath: String? = null,
    val mediaThumbnailPath: String? = null,
    val minithumbnail: ByteArray? = null,
    val date: Int,
    val isOutgoing: Boolean,
    val isRead: Boolean,
    val replyMarkupData: String? = null,
    val reactionsData: String? = null,
    val replyToMessageId: Long = 0L,
    val replyToPreview: String? = null,
    val replyToPreviewType: String? = null,
    val replyToPreviewText: String? = null,
    val replyToPreviewSenderName: String? = null,
    val replyCount: Int = 0,
    val threadId: Long? = null,
    val viaBotUserId: Long = 0L,
    val viaBotName: String? = null,
    val senderPersonalAvatarPath: String? = null,
    val senderCustomTitle: String? = null,
    val isSenderAdmin: Boolean = false,
    val isSenderVerified: Boolean = false,
    val isSenderPremium: Boolean = false,
    val senderStatusEmojiId: Long = 0L,
    val senderStatusEmojiPath: String? = null,
    val forwardFromName: String? = null,
    val forwardFromId: Long = 0L,
    val forwardOriginChatId: Long? = null,
    val forwardOriginMessageId: Long? = null,
    val forwardDate: Int = 0,
    val editDate: Int = 0,
    val canBeEdited: Boolean = false,
    val canBeForwarded: Boolean = true,
    val canBeDeletedOnlyForSelf: Boolean = true,
    val canBeDeletedForAllUsers: Boolean = false,
    val canBeSaved: Boolean = true,
    val canGetMessageThread: Boolean = false,
    val canGetStatistics: Boolean = false,
    val canGetRevenueStatistics: Boolean = false,
    val canGetMediaStatistics: Boolean = false,
    val canGetReadReceipts: Boolean = false,
    val canGetViewers: Boolean = false,
    val readDate: Int = 0,
    val hasUnreadMention: Boolean = false,
    val hasUnreadReactions: Boolean = false,
    val isPinned: Boolean = false,
    val containsUnreadPollVotes: Boolean = false,
    val suggestedPostInfoData: String? = null,
    val factCheckData: String? = null,
    val mediaAlbumId: Long = 0L,
    val entities: String? = null,
    val viewCount: Int = 0,
    val forwardCount: Int = 0,
    val createdAt: Long = System.currentTimeMillis()
)